import { Rooms } from '../server/rooms.js';
let fails = 0;
const check = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) fails++; };
const r = new Rooms();
const { room } = r.create('a', 'Host');
check('host is commander', room.players.get('a').role === 'commander');
check('code is 4 letters', /^[A-Z]{4}$/.test(room.code));
check('join works (lowercase code)', !r.join(room.code.toLowerCase(), 'b', 'Bea').error);
r.join(room.code, 'c', 'Cy'); r.join(room.code, 'd', 'Di');
check('roles are all different', new Set([...room.players.values()].map(p => p.role)).size === 4);
check('5th player rejected', !!r.join(room.code, 'e', 'Ed').error);
check('wrong code rejected', !!r.join('QQQQ', 'f', 'X').error);
check('cannot take a used role', r.setRole('b', 'commander') === null);
check('cannot start until ready', !!r.start('a').error);
['b', 'c', 'd'].forEach(id => r.setReady(id, true));
check('only host starts', !!r.start('b').error);
check('host can start when all ready', !r.start('a').error && room.phase === 'playing');
check('cannot join after start', !!r.join(room.code, 'z', 'Z').error);
check('member leaves, room stays', r.leave('d').closed === false && room.players.size === 3);
check('host leaves, room closes', r.leave('a').closed === true && r.rooms.size === 0);
console.log(fails ? fails + ' FAILED' : 'ALL ROOM TESTS PASSED');
process.exit(fails ? 1 : 0);
